// The token radar's model, version radar-2: one snapshot of the protocol universe in, one ranked
// board out.
//
// The board ranks every rankable pre-token protocol in the snapshot: the 40 on the watchlist plus
// every other pre-token protocol that is not an exchange and not a versioned pool of another protocol.
// A protocol is pre-token when its record carries no token at all (no market cap, no CoinGecko id, no
// symbol). The snapshot's live-token protocols are kept apart and shown with the market's own values,
// never mixed into the ranked board.
//
// Implied value follows only from the snapshot's own figures. The base multiple is not a guess: it is
// calibrated from the protocols in the same snapshot whose tokens already trade. For each category the
// model takes the median market-cap-to-TVL ratio of its live-token peers (five peers or more); a
// category with too few peers falls back to the median across every live-token protocol. So a lending
// protocol is priced like lending tokens trade, a DEX like DEX tokens trade, and no protocol name is
// ever special-cased: the same function scores every row.
//
//   multiple   = category median mcap/tvl (5+ peers) else the global median, clamped to [0.02, 1.5]
//   base       = tvl_usd x multiple
//   growth     = clamp(change_7d, -60, 120) per cent
//   growthMult = 1 + (growth / 100) x 0.5
//   maturity   = 0.6 + min(age_days, 1095) / 1095 x 0.4   (age_days unknown: 365)
//   chains     = 1 + 0.02 x min(chains - 1, 10)
//   implied    = max(1, round(base x growthMult x maturity x chains))
//
// Age is the time since DefiLlama first listed the protocol: the best record of how long it has run
// with no token. The farm plan is derived from the same record (category, chains, TVL, age), never
// from a hand-written list of names.

/** The snapshot's protocol entry: exactly the ten fields the sealed input carries. */
export interface SnapshotProtocol {
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
}

/** The whole snapshot document. */
export interface Snapshot {
  as_of: string;
  source: string;
  floor_usd: number;
  protocols: SnapshotProtocol[];
  watchlist: string[];
}

